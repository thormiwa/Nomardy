def normalize_destination(destination: str) -> str:
    normalized = " ".join(destination.strip().lower().split())
    return DESTINATION_ALIASES.get(normalized, normalized)


def get_nigerian_visa_requirement(destination: str) -> Dict[str, Any]:
    key = normalize_destination(destination)
    if key not in MOCK_VISA_DATA:
        raise KeyError(destination)
    return MOCK_VISA_DATA[key]
